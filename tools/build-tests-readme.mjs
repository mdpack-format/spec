// Builds tests/README.md from tests/expectations.json.
//
// The corpus index is generated rather than written by hand for the same reason
// expectations.json is: a table that lists 41 packages will drift from the
// packages themselves the first time one is added, and a conformance corpus
// that misdescribes itself is worse than one with no index at all.
//
// Usage: node tools/build-tests-readme.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const expectations = JSON.parse(readFileSync(join(root, 'tests', 'expectations.json'), 'utf8'));

const lines = [];

lines.push('# MDPack conformance corpus');
lines.push('');
lines.push(`Packages for testing MDPack ${expectations.specification} implementations: ` +
    `${expectations.valid.length} that a Conforming Reader must accept and ` +
    `${expectations.invalid.length} that it must reject.`);
lines.push('');
lines.push('Expected outcomes are machine-readable in [`expectations.json`](expectations.json), so a');
lines.push('test suite can iterate the corpus rather than hard-code a list. This page is generated');
lines.push('from that file by `tools/build-tests-readme.mjs`; the packages themselves are generated by');
lines.push('`tools/build-corpus.mjs`. Neither is meant to be edited by hand.');
lines.push('');
lines.push('A rejection must name a reason. Reporting *why* a package was refused is what lets an');
lines.push('application tell a user to upgrade rather than implying their file is corrupt, which is');
lines.push('why §8.9 requires the failure modes to be distinguishable.');
lines.push('');

lines.push('## Error classes');
lines.push('');
lines.push('| Class | Meaning |');
lines.push('|---|---|');
for (const [name, meaning] of Object.entries(expectations.errorClasses)) {
    lines.push(`| \`${name}\` | ${meaning} |`);
}
lines.push('');

lines.push('## Valid packages');
lines.push('');
lines.push('Every one of these must be accepted.');
lines.push('');
lines.push('| Package | What it covers |');
lines.push('|---|---|');
for (const entry of expectations.valid) {
    lines.push(`| [\`${entry.file}\`](valid/${entry.file}) | ${entry.description} |`);
}
lines.push('');

lines.push('## Invalid packages');
lines.push('');
lines.push('Every one of these must be rejected, with one of the listed error classes. A reader that');
lines.push('accepts any of them is not conforming, and a reader that crashes on one is a liability:');
lines.push('several of these files are what a hostile package looks like.');
lines.push('');
lines.push('| Package | Why it is invalid | Expected class |');
lines.push('|---|---|---|');
for (const entry of expectations.invalid) {
    const classes = entry.errors.map(error => `\`${error}\``).join(' or ');
    lines.push(`| [\`${entry.file}\`](invalid/${entry.file}) | ${entry.description} | ${classes} |`);
}
lines.push('');

lines.push('## Regenerating');
lines.push('');
lines.push('```sh');
lines.push('node tools/build-corpus.mjs       # packages and expectations.json');
lines.push('node tools/build-tests-readme.mjs # this page');
lines.push('```');
lines.push('');
lines.push('The packages are byte-exact fixtures. `.gitattributes` pins `*.mdpack` as binary, because');
lines.push('line-ending normalisation silently corrupts a ZIP archive and the corpus would then test');
lines.push('nothing but the reader\'s error paths.');
lines.push('');

writeFileSync(join(root, 'tests', 'README.md'), lines.join('\n'), 'utf8');
console.log(`tests/README.md written: ${expectations.valid.length} valid, ${expectations.invalid.length} invalid`);
